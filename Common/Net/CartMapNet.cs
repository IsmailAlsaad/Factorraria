using Factorraria.Common.Carts;
using System;
using System.Collections.Concurrent;
using System.Collections.Generic;
using System.IO;
using Terraria;
using Terraria.ID;
using Terraria.ModLoader;

namespace Factorraria.Common.Net
{
    /// <summary>One cart as the map sees it: where it is, what it looks like, what module it carries.</summary>
    public sealed class CartMapEntry
    {
        public int Id;
        public float TileX;      // tile coordinates of the middle of the tile the cart is on (what MapOverlayDrawContext.Draw wants)
        public float TileY;
        public CartModule Module;
        public int Facing = 1;   // 1 = facing right, -1 = left (the icon is flipped to match)
        public int SkinType;     // item type of the skin (the cart's item sprite is the icon)
        public int ModuleItemType; // item type drawn on top (chest, terrarium), 0 = nothing
        public string SkinKey;   // wire keys, only filled on the server
        public string ModuleItemKey;
    }

    /// <summary>
    /// Cart map snapshot (side feature, multiplayer-first).
    ///
    /// Authority: the server (or single-player) owns every cart. CartNet only replicates carts near a player, so the map cannot use it.
    /// This is a second, tiny channel just for the map: a list of every PLAYER-PLACED cart (Cart.PlacedByPlayer) with its tile, skin key,
    /// module and module item key. Carts generated by world generation are never in it.
    ///  - Server: every ResendIntervalTicks ticks it builds the list, hashes it and sends it to each subscribed client whose last hash differs.
    ///    A client that just subscribed has no hash, so it gets the full list at the next tick. Sending only on change keeps idle worlds free.
    ///  - Client: the handler parses and swaps one array reference (packet handlers run off the main thread; a reference swap is safe).
    ///  - Single-player and host: no packet, Collect reads CartSystem.Carts directly (rebuilt a few times a second).
    /// The toggle (off / all / motor only) is purely local, it never goes on the wire.
    /// </summary>
    public static class CartMapNet
    {
        public static int ResendIntervalTicks = 120;
        public static int MaxEntries = 1000;
        public static int LocalRefreshTicks = 1;   // single-player only (a multiplayer client uses the server snapshot every ResendIntervalTicks)

        static CartMapEntry[] clientEntries = Array.Empty<CartMapEntry>();
        static readonly ConcurrentDictionary<int, int> lastSentHash = new();
        static readonly List<CartMapEntry> localCache = new();
        static uint lastLocalBuild;
        static int tick;

        public static int ServerSent;
        public static int ClientReceived;

        public static void Reset()
        {
            clientEntries = Array.Empty<CartMapEntry>();
            lastSentHash.Clear();
            localCache.Clear();
            lastLocalBuild = 0;
            tick = 0;
            ServerSent = ClientReceived = 0;
        }

        public static void OnDisconnect(int who)
        {
            lastSentHash.TryRemove(who, out _);
        }

        // ---------------------------------------------------------------- reading (map layer, any mode)

        /// <summary>Fills the list with every player-placed cart the local map should know about.</summary>
        public static void Collect(List<CartMapEntry> into)
        {
            into.Clear();

            if (Main.netMode == NetmodeID.MultiplayerClient)
            {
                into.AddRange(clientEntries);
                return;
            }

            if (Main.GameUpdateCount - lastLocalBuild >= (uint)Math.Max(1, LocalRefreshTicks))
            {
                lastLocalBuild = Main.GameUpdateCount;
                localCache.Clear();
                BuildFromWorld(localCache, false);
            }

            into.AddRange(localCache);
        }

        // Returns a hash of everything the map shows, so the server can skip clients that already have this exact picture.
        static int BuildFromWorld(List<CartMapEntry> into, bool withKeys)
        {
            int hash = 0;

            for (int i = 0; i < CartSystem.Carts.Count && into.Count < MaxEntries; i++)
            {
                Cart cart = CartSystem.Carts[i];
                if (!cart.Active || !cart.PlacedByPlayer)
                    continue;

                CartMapEntry entry = new CartMapEntry();
                entry.Id = cart.Id;
                // The server snapshot (withKeys) sends whole tiles; the local list (single-player) uses the exact position so the icon glides.
                entry.TileX = withKeys ? (int)(cart.Position.X / 16f) + 0.5f : cart.Position.X / 16f;
                entry.TileY = withKeys ? (int)(cart.Position.Y / 16f) + 0.5f : cart.Position.Y / 16f;
                entry.Module = cart.Module;
                entry.Facing = cart.Facing < 0 ? -1 : 1;
                entry.SkinType = cart.SkinType;
                entry.ModuleItemType = cart.ModuleItem > 0 ? cart.ModuleItem : Cart.ModuleItemType(cart.Module);

                if (withKeys)
                {
                    entry.SkinKey = cart.Skin;
                    entry.ModuleItemKey = entry.ModuleItemType > 0 ? CartSkins.KeyOf(entry.ModuleItemType) : null;
                }

                hash = HashCode.Combine(hash, entry.Id, (int)entry.TileX, (int)entry.TileY, (int)entry.Module, entry.SkinType, entry.ModuleItemType, entry.Facing);
                into.Add(entry);
            }

            return hash;
        }

        // ---------------------------------------------------------------- server

        public static void ServerTick()
        {
            if (Main.netMode != NetmodeID.Server)
                return;

            tick++;
            if (tick % Math.Max(1, ResendIntervalTicks) != 0)
                return;

            List<CartMapEntry> entries = null;
            int hash = 0;

            for (int who = 0; who < Main.maxPlayers; who++)
            {
                if (!Main.player[who].active || !CartNet.IsSubscribed(who))
                {
                    lastSentHash.TryRemove(who, out _);
                    continue;
                }

                if (entries == null)
                {
                    entries = new List<CartMapEntry>();
                    hash = BuildFromWorld(entries, true);
                }

                if (lastSentHash.TryGetValue(who, out int last) && last == hash)
                    continue;

                lastSentHash[who] = hash;
                Send(who, entries);
            }
        }

        static void Send(int who, List<CartMapEntry> entries)
        {
            int count = Math.Min(entries.Count, MaxEntries);
            List<string> table = new List<string>();
            Dictionary<string, int> index = new Dictionary<string, int>();
            ushort[] skinIndex = new ushort[count];
            ushort[] moduleIndex = new ushort[count];

            for (int i = 0; i < count; i++)
            {
                skinIndex[i] = Intern(entries[i].SkinKey, table, index);
                moduleIndex[i] = Intern(entries[i].ModuleItemKey, table, index);
            }

            FactorrariaNet.SendToClient(who, FactorrariaPacket.CartMapSnapshot, writer =>
            {
                writer.Write((ushort)table.Count);
                for (int i = 0; i < table.Count; i++)
                    writer.Write(table[i]);

                writer.Write((ushort)count);
                for (int i = 0; i < count; i++)
                {
                    CartMapEntry entry = entries[i];
                    writer.Write(entry.Id);
                    writer.Write((short)(int)entry.TileX);
                    writer.Write((short)(int)entry.TileY);
                    writer.Write((byte)entry.Module);
                    writer.Write((sbyte)entry.Facing);
                    writer.Write(skinIndex[i]);
                    writer.Write(moduleIndex[i]);
                }
            });

            ServerSent++;
        }

        // Skin and module item keys repeat a lot (hundreds of Minecarts), so each distinct key goes on the wire once. 0xFFFF = none.
        static ushort Intern(string key, List<string> table, Dictionary<string, int> index)
        {
            if (string.IsNullOrEmpty(key))
                return ushort.MaxValue;

            if (!index.TryGetValue(key, out int found))
            {
                found = table.Count;
                table.Add(key);
                index[key] = found;
            }

            return (ushort)found;
        }

        // ---------------------------------------------------------------- client

        public static void HandleSnapshot(BinaryReader reader, int sender)
        {
            if (Main.netMode != NetmodeID.MultiplayerClient)
                return;

            int tableCount = reader.ReadUInt16();
            string[] table = new string[tableCount];
            for (int i = 0; i < tableCount; i++)
                table[i] = reader.ReadString();

            int count = reader.ReadUInt16();
            CartMapEntry[] entries = new CartMapEntry[count];

            for (int i = 0; i < count; i++)
            {
                CartMapEntry entry = new CartMapEntry();
                entry.Id = reader.ReadInt32();
                entry.TileX = reader.ReadInt16() + 0.5f;
                entry.TileY = reader.ReadInt16() + 0.5f;
                entry.Module = (CartModule)reader.ReadByte();
                entry.Facing = reader.ReadSByte() < 0 ? -1 : 1;
                int skinIndex = reader.ReadUInt16();
                int moduleIndex = reader.ReadUInt16();

                if (skinIndex >= tableCount || !CartSkins.TryTypeOf(table[skinIndex], out entry.SkinType))
                    entry.SkinType = ItemID.Minecart;

                if (moduleIndex < tableCount && CartSkins.TryTypeOf(table[moduleIndex], out int moduleItem))
                    entry.ModuleItemType = moduleItem;
                else
                    entry.ModuleItemType = Cart.ModuleItemType(entry.Module);

                entries[i] = entry;
            }

            clientEntries = entries;
            ClientReceived++;
        }
    }

    public class CartMapNetSystem : ModSystem
    {
        public override void Load()
        {
            FactorrariaNet.Register(FactorrariaPacket.CartMapSnapshot, PacketDirection.ToClient, CartMapNet.HandleSnapshot);
            JoinSync.RegisterDisconnectHook(CartMapNet.OnDisconnect);
        }

        public override void OnWorldLoad() => CartMapNet.Reset();

        public override void OnWorldUnload() => CartMapNet.Reset();

        // PostUpdateEverything runs on every side; ServerTick only does something on a dedicated server.
        public override void PostUpdateEverything() => CartMapNet.ServerTick();
    }
}